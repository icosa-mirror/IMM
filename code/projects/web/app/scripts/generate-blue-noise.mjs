import { readFile, writeFile } from "node:fs/promises";
import { resolve } from "node:path";

const sourcePath = resolve(import.meta.dirname, "../../../../libImmPlayer/src/blue_noise.cpp");
const outputPath = resolve(import.meta.dirname, "../src/render-three/blue-noise-data.ts");
const source = await readFile(sourcePath, "utf8");
const values = [...source.matchAll(/0x([0-9a-f]+)/gi)].map((match) => Number.parseInt(match[1], 16));
const expectedLength = 64 * 64 * 64;
if (values.length !== expectedLength) {
    throw new Error(`Expected ${expectedLength} native blue-noise bytes, found ${values.length}`);
}
const encoded = Buffer.from(values).toString("base64");
const chunks = encoded.match(/.{1,120}/g) ?? [];
const generated = `// Generated from code/libImmPlayer/src/blue_noise.cpp by scripts/generate-blue-noise.mjs.\n`
    + `// Do not edit this file by hand.\n`
    + `export const IMM_BLUE_NOISE_64_BASE64 =\n    "${chunks.join(`"\n    + "`)}";\n`;
await writeFile(outputPath, generated);
console.log(`Generated ${expectedLength} native blue-noise bytes`);
